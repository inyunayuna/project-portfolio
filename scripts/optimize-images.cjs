// npm install --prefix scripts && node scripts/optimize-images.cjs
// Original images and JSON are never modified. Run prepare-site.py afterwards.
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const widths = [640, 960, 1600, 2400];
// Text-heavy interface captures: no additional compression loss after resizing.
const losslessImages = new Set([
  'assets/images/projects/project-2/stillcut_5.png',
  'assets/images/projects/project-2/stillcut_6.png',
]);

async function collect(dir) {
  const result = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...await collect(file));
    else if (/\.(png|jpe?g|webp)$/i.test(file)) result.push(file);
  }
  return result.sort();
}

(async () => {
  const manifest = {};
  const output = path.join(root, 'assets/optimized');
  await fs.mkdir(output, { recursive: true });
  for (const file of await collect(path.join(root, 'assets/images'))) {
    const src = path.relative(root, file).split(path.sep).join('/');
    const input = await fs.readFile(file);
    const metadata = await sharp(input).metadata();
    // autoOrient dimensions match the pixels produced by rotate().
    const { width, height } = metadata.autoOrient || metadata;
    const lossless = losslessImages.has(src);
    const variants = [];
    const targets = [...new Set(widths.map(w => Math.min(w, width)))];
    for (const target of targets) {
      const buffer = await sharp(input).rotate()
        .resize({ width: target, withoutEnlargement: true })
        .webp({ quality: 92, lossless, effort: 6 }).toBuffer();
      const hash = crypto.createHash('sha256').update(buffer).digest('hex').slice(0, 16);
      const name = `${hash}-${target}.webp`;
      await fs.writeFile(path.join(output, name), buffer);
      variants.push({ src: `assets/optimized/${name}`, width: target });
    }
    manifest[src] = { width, height, variants };
    console.log(`${src}: ${width}×${height}, ${lossless ? 'lossless' : 'quality 92'}, ${variants.length} sizes`);
  }
  await fs.writeFile(path.join(root, 'js/image-manifest.js'),
    '// Generated by scripts/optimize-images.cjs; original paths remain the content API.\n' +
    `export const imageManifest = ${JSON.stringify(manifest, null, 2)};\n`);
})().catch(error => { console.error(error); process.exitCode = 1; });
